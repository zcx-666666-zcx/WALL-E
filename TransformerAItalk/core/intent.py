"""
意图识别模块（Intent Recognition）
────────────────────────────────────────────────────────────────
职责：
  · 接收语音转文字后的文本
  · 通过关键词匹配判断是机器人指令还是对话请求
  · 指令直接返回对应编号，对话请求返回 0

指令编号：
  1 → 前进
  2 → 后退
  3 → 左转
  4 → 右转
  5 → 开启自动跟随
  6 → 关闭自动跟随
  0 → 非指令，进入对话流程
"""

from __future__ import annotations

# ════════════════════════════════════════════
# 关键词配置（自己按需增删）
# ════════════════════════════════════════════

INTENT_KEYWORDS: dict[int, list[str]] = {
    1: [
        "前进", "向前", "往前",
        "前走", "向前走", "直走", "直行",
    ],
    2: [
        "后退", "向后", "往后", "退一退",
        "向后走", "倒退",
    ],
    3: [
        "左转", "向左", "往左", 
        "左拐", "向左转",
    ],
    4: [
        "右转", "向右", "往右",
        "右拐", "向右转",
    ],
    5: [
        "停下","停", "别走了",
        "停止", "别动",
    ],
    6: [
        "开启自动跟随", "开始自动跟随", "跟着我",
        "跟我走", "跟上来", "开始跟随", "打开跟随",
        "启动跟随", "跟随模式", "开启跟随模式",
    ],
    7: [
        "关闭自动跟随", "停止自动跟随", "取消跟随", "别跟了",
        "不用跟了", "关跟随", "关掉跟随", "别跟我了",
        "停止跟随", "退出跟随", "关闭跟随模式",
    ],
}


# ════════════════════════════════════════════
# 识别函数
# ════════════════════════════════════════════

def recognize_intent(text: str) -> int:
    """
    识别文本意图

    返回值：
      1-7 → 对应机器人指令
      0   → 非指令，应进入对话流程

    示例：
      recognize_intent("向前走")   → 1
      recognize_intent("右转一下") → 4
      recognize_intent("我今天很累") → 0
    """
    text = text.strip()
    if not text:
        return 0

    for intent_id, keywords in INTENT_KEYWORDS.items():
        for kw in keywords:
            if kw in text:
                return intent_id

    return 0


# ════════════════════════════════════════════
# 指令描述（可选，用于日志和调试）
# ════════════════════════════════════════════

INTENT_LABELS = {
    0: "对话",
    1: "前进",
    2: "后退",
    3: "左转",
    4: "右转",
    5: "停下",
    6: "开启自动跟随",
    7: "关闭自动跟随",
}


def recognize_with_label(text: str) -> tuple[int, str]:
    """返回 (意图编号, 意图描述)，方便调试"""
    intent = recognize_intent(text)
    return intent, INTENT_LABELS[intent]
